import { Geometry } from '../ogl2.js';

export function generateCuboidVertices(p0, p1, p2, p3, p4, p5, p6, p7) {
    const vertices = new Float32Array();
    // Front face
    vertices.push(...p0, ...p1, ...p2, ...p0, ...p2, ...p3);
    // Back face
    vertices.push(...p4, ...p5, ...p6, ...p4, ...p6, ...p7);
    return vertices;
}

